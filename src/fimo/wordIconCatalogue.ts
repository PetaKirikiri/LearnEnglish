export type WordIcon = {
  asset?: string
  symbol?: IconSymbol
  cue?: IconCue
  secondary?: string
  value?: string
  description: string
}

export const wordIcons: Record<string, WordIcon> = {}
function add(words: string, icon: WordIcon) {
  for (const word of words.split(' ')) {
    if (wordIcons[word]) throw new Error(`Duplicate word icon: ${word}`)
    wordIcons[word] = icon
  }
}
