import { beforeEach, expect, it, vi } from 'vitest'
const mocks = vi.hoisted(() => ({ getSession:vi.fn(), getUser:vi.fn(), setSession:vi.fn(), invoke:vi.fn(), init:vi.fn(), getIDToken:vi.fn(), getAccessToken:vi.fn() }))
vi.mock('../lib/supabase', () => ({supabase:{auth:mocks,functions:{invoke:mocks.invoke}}}))
vi.mock('@line/liff', () => ({default:mocks}))
beforeEach(() => {
 vi.resetModules(); vi.resetAllMocks()
 window.history.replaceState({}, "", "/english/practice")
 mocks.getSession.mockResolvedValue({data:{session:null}})
 mocks.init.mockResolvedValue(undefined)
 mocks.getIDToken.mockReturnValue('verified-by-server')
 mocks.getAccessToken.mockReturnValue('line-access')
 mocks.setSession.mockResolvedValue({data:{user:{id:'member'}},error:null})
})
it('recognises an existing LINE member directly through the shared service', async()=>{
 mocks.invoke.mockResolvedValue({data:{access_token:'a',refresh_token:'r'}})
 const {recogniseHomeworkAccount}=await import('./homeworkLine')
 expect(await recogniseHomeworkAccount()).toBe('member')
 expect(mocks.init).toHaveBeenCalledWith({liffId:'2010311582-ziuNvGjb',withLoginOnExternalBrowser:false})
 expect(mocks.invoke).toHaveBeenCalledWith('line-liff-recognize',expect.objectContaining({body:{id_token:'verified-by-server'}}))
})
it('automatically connects a new learner without a welcome step', async()=>{
 mocks.invoke.mockResolvedValueOnce({data:{recognised:false}}).mockResolvedValueOnce({data:{access_token:'a',refresh_token:'r'}})
 const {recogniseHomeworkAccount}=await import('./homeworkLine')
 expect(await recogniseHomeworkAccount()).toBe('member')
 expect(mocks.invoke).toHaveBeenLastCalledWith('line-liff-auth',expect.objectContaining({body:{id_token:'verified-by-server',access_token:'line-access'}}))
})
it('uses a validated existing session',async()=>{
 mocks.getSession.mockResolvedValue({data:{session:{}}})
 mocks.getUser.mockResolvedValue({data:{user:{id:'existing'}},error:null})
 const {recogniseHomeworkAccount}=await import('./homeworkLine')
 expect(await recogniseHomeworkAccount()).toBe('existing')
 expect(mocks.init).not.toHaveBeenCalled()
})
it('does not call the account service without a LINE token',async()=>{
 mocks.getIDToken.mockReturnValue(null)
 const {recogniseHomeworkAccount}=await import('./homeworkLine')
 await expect(recogniseHomeworkAccount()).rejects.toThrow('LINE')
 expect(mocks.invoke).not.toHaveBeenCalled()
})

it('initialises LINE deep links even with an existing account',async()=>{
 window.history.replaceState({}, '', '/english/practice?liff.state=%3Fview%3Dscoreboard')
 mocks.getSession.mockResolvedValue({data:{session:{}}})
 mocks.getUser.mockResolvedValue({data:{user:{id:'existing'}},error:null})
 const {recogniseHomeworkAccount,homeworkDestination}=await import('./homeworkLine')
 expect(await recogniseHomeworkAccount()).toBe('existing')
 expect(mocks.init).toHaveBeenCalledTimes(1)
 expect(homeworkDestination()).toBe('scoreboard')
 expect(homeworkDestination('?view=scoreboard')).toBe('scoreboard')
 expect(homeworkDestination('?liff.state=%3Flesson%3D2')).toBe('practice')
})
