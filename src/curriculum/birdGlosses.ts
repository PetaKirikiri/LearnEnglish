function splitUnit(unit:ReadingUnit):ReadingUnit[] {
  const key=unit.english.toLowerCase().replace(/[?.]/g,'')
  const split=splits[key]
  if(!split) return [unit]
  const parts=split[0].split('|'),meanings=split[1].split('|')
  let cursor=0
  return parts.map((part,index)=>{
    const english=unit.english.slice(cursor,cursor+part.length)+(index===parts.length-1?unit.english.slice(cursor+part.length):'')
    cursor+=part.length+1
    return {english,thai:meanings[index]}
  })
}
export const birdGlosses = new Map<string,ReadingUnit[]>(rows.map(([english,thai])=>{
  const source=english.split('|'), meanings=thai.split('|')
  if(source.length!==meanings.length) throw new Error(`Misaligned bird gloss: ${english}`)
  return [source.join(' '),source.flatMap((word,index)=>splitUnit({english:word,thai:meanings[index]}))]
}))

export function glossBirdSentence(english:string):ReadingUnit[] {
  const units=birdGlosses.get(plainBirdSentence(english))
  if(!units) throw new Error(`Missing contextual reading gloss: ${english}`)
  return units
}
