it('does not offer driving for the child shown by a son noun subject',async()=>{
 const {everydayPeopleCatalogue}=await import('../everydayVocabulary')
 const host=document.createElement('div'),root=createRoot(host)
 try{
  await act(async()=>root.render(<SentenceMatrix lesson={{id:'children-actions',pattern:'present-action',vocabulary:[...testVocabulary,...everydayPeopleCatalogue],plural:true,initialWord:'son'}} initialAction={{action:'driving',personMode:'noun',personWord:'the son'}} settings={{audio:false,initialPattern:'answer'}}/>))
  expect(host.textContent).not.toContain('driving')
  expect(host.querySelector('.cw-sentence-board')?.getAttribute('aria-label')).not.toContain('driving')
  await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="Change action"]')!.click())
  expect([...host.querySelectorAll('.cw-word-chip strong')].map(n=>n.textContent)).not.toContain('driving')
  for(const mode of ['name','pronoun','noun']){
   await act(async()=>host.querySelector<HTMLButtonElement>(`[aria-label="Subject block mode"] [data-noun-mode="${mode}"]`)!.click())
   expect(host.querySelector('.cw-sentence-board')?.getAttribute('aria-label')).not.toContain('driving')
   await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="Change action"]')!.click())
   expect([...host.querySelectorAll('.cw-word-chip strong')].map(n=>n.textContent)).not.toContain('driving')
  }
 }finally{await act(async()=>root.unmount())}
})
