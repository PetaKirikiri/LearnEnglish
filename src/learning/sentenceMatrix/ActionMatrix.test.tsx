it('uses the shared education window, updates choices there and restores the original card',async()=>{
 const host=document.createElement('div');document.body.append(host);const root=createRoot(host)
 const click=async(selector:string)=>act(async()=>host.querySelector<HTMLButtonElement>(selector)!.click())
 try{
  await act(async()=>root.render(<SentenceMatrix lesson={{id:'actions',pattern:'present-action',vocabulary:testVocabulary,plural:true,initialWord:'eating'}} settings={{audio:false}}/>))
  await click('[aria-label="Next pattern"]')
  await click('[aria-label="Slot 3: eating"]')
  expect(host.querySelector('.cw-word-heading h1')?.textContent).toBe('eating')
  expect(host.querySelector('.cw-reference-sheet')).not.toBeNull()
  expect(host.querySelector('.pronunciation-comparison')).not.toBeNull()
  await click('[data-category="places"]')
  expect([...host.querySelectorAll('.cw-word-chip strong')].map(e=>e.textContent)).toEqual(['walking','going','leaving'])
  await click('[data-word="going"]')
  expect(host.querySelector('.cw-word-heading h1')?.textContent).toBe('going')
  expect(host.textContent).toContain('ฉันกำลังไปที่โรงแรม')
  await click('.cw-word-return')
  expect(host.querySelector('.cw-sentence-board')?.getAttribute('aria-label')).toBe('I am going to the hotel.')
  expect(document.activeElement?.getAttribute('aria-label')).toBe('Slot 3: going')
  await click('[aria-label="Change object"]')
  await click('[data-category="places"]')
  expect([...host.querySelectorAll('.cw-word-chip strong')].map(e=>e.textContent)).toEqual(['toilet','restaurant','hotel','gym'])
  await click('[aria-label="Close word picker"]')
  expect(document.activeElement?.getAttribute('aria-label')).toBe('Change object')
 }finally{await act(async()=>root.unmount());host.remove()}
})
