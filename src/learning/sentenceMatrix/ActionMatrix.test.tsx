it('requests shared noun modes for both blocks and keeps compatible selections',async()=>{
 const host=document.createElement('div'),root=createRoot(host)
 const click=async(selector:string)=>act(async()=>host.querySelector<HTMLButtonElement>(selector)!.click())
 try{
  await act(async()=>root.render(<SentenceMatrix lesson={{id:'actions',pattern:'present-action',initialWord:'eating',plural:true,vocabulary:[...testVocabulary,{word:'doctor',thai:'หมอ',categories:['people']}],subjectModes:{pronouns:[],names:[{word:'Bia',thai:'เบีย',kind:'person'},{word:'Central',thai:'เซ็นทรัล',kind:'place'}]}}} settings={{audio:false}}/>))
  await click('[aria-label="Next pattern"]')
  await click('[aria-label="Subject block mode"] [data-noun-mode="name"]')
  expect(host.querySelector('.cw-sentence-board')?.getAttribute('aria-label')).toBe('Bia is eating an apple.')
  await click('[aria-label="Subject block mode"] [data-noun-mode="noun"]')
  expect(host.querySelector('.cw-sentence-board')?.getAttribute('aria-label')).toBe('The man is eating an apple.')
  expect([...host.querySelectorAll('.cw-noun-group .example-source')].map(e=>e.textContent)).toEqual(['The','man','an','apple.'])
  expect(host.querySelector<HTMLButtonElement>('[aria-label="Object block mode"] [data-noun-mode="name"]')?.disabled).toBe(true)
  await click('[aria-label="Change action"]');await click('[data-word="going"]')
  await click('[aria-label="Object block mode"] [data-noun-mode="name"]')
  expect(host.querySelector('.cw-sentence-board')?.getAttribute('aria-label')).toBe('The man is going to Central.')
  expect(host.querySelector<HTMLButtonElement>('[aria-label="Subject block mode"] [data-noun-mode="pronoun"]')?.disabled).toBe(true)
  expect(host.querySelector('.cw-sentence-board')?.getAttribute('aria-label')).toBe('The man is going to Central.')
  await click('[aria-label="Change action"]')
  expect(host.querySelector('[data-word="sleeping"]')).toBeNull()
  await click('[data-word="driving"]')
  expect(host.querySelector('.cw-sentence-board')?.getAttribute('aria-label')).toBe('The man is driving to the hotel.')
  expect(host.querySelector('[aria-label="Object block mode"]')).not.toBeNull()
 }finally{await act(async()=>root.unmount())}
})

