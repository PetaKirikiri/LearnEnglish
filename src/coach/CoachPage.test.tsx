// @vitest-environment happy-dom
import { act } from 'react'
import { createRoot } from 'react-dom/client'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import CoachPage from './CoachPage'
import { PETA_ACCOUNT_ID } from '../auth/appAccess'
import { loadProgress, loadWords, memoryKey, progressKey, questions } from './course'
import { coachLineEntryUrl, isCoachLineEntry } from './lineEntry'
const account = vi.hoisted(() => ({ finish: vi.fn(async (): Promise<{ id: string } | null> => null) }))
const speech = vi.hoisted(() => ({ speak: vi.fn(), stop: vi.fn() }))
vi.mock('../hotel/accountHandoff', () => ({ finishHotelReturn: account.finish }))
vi.mock('../learning/speech', () => ({ speakEnglish: speech.speak, stopEnglishSpeech: speech.stop }))
Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true })
const host = document.createElement('div'); document.body.append(host)
let root = createRoot(host)
beforeEach(() => { window.location.href = 'https://learn-english-coral.vercel.app/padel-coach'; account.finish.mockResolvedValue(null) })
afterEach(async () => { await act(() => root.unmount()); root = createRoot(host); localStorage.clear(); vi.restoreAllMocks(); vi.clearAllMocks(); vi.unstubAllEnvs() })
const answer = (text: string) => [...host.querySelectorAll<HTMLButtonElement>('.hotel-answer')].find(b => b.textContent === text)!

it('uses Thai audio and French binary answers; gates answers on listening; only advances manually', async () => {
  account.finish.mockResolvedValue({ id: 'coach' }); vi.spyOn(Math, 'random').mockReturnValue(0)
  await act(() => root.render(<CoachPage />))
  expect(host.querySelector('.padel-brand span')?.textContent).toBe('PADEL COACH')
  expect(speech.speak.mock.calls[0][0]).toBe(questions[0].thai)
  expect(host.querySelectorAll('.hotel-answer')).toHaveLength(2)
  expect(host.querySelector('.right')).toBeNull()
  const correct = answer('Très bien.')
  expect(correct.disabled).toBe(true)
  await act(() => correct.click())
  expect(localStorage.getItem(progressKey('coach'))).toBeNull()
  await act(() => speech.speak.mock.calls[0][2]('ended'))
  await act(() => { correct.click(); correct.click() })
  expect(loadProgress('coach')[questions[0].id].attempts).toBe(1)
  expect(loadWords('coach').ดี.strength).toBe(1)
  expect(localStorage.getItem('hotel:v1:coach')).toBeNull()
  expect(localStorage.getItem('padel:v1:coach')).toBeNull()
  expect(speech.speak).toHaveBeenCalledTimes(1)
  await act(() => host.querySelector<HTMLButtonElement>('.hotel-primary')!.click())
  expect(speech.speak.mock.calls[1][0]).toBe('ตีลูก')
})
it('supports Thai chunks and French help, without help counting as mastery', async () => {
  account.finish.mockResolvedValue({ id: 'coach' }); vi.spyOn(Math, 'random').mockReturnValue(0)
  localStorage.setItem(memoryKey('coach'), JSON.stringify({ ดี: { seen: 8, strength: 8 } }))
  await act(() => root.render(<CoachPage />))
  const tokens = host.querySelectorAll<HTMLElement>('.coach-token')
  expect(tokens[0].style.opacity).toBe('0.2'); expect(tokens[1].style.opacity).toBe('1')
  await act(() => tokens[0].click())
  expect(host.querySelector<HTMLDialogElement>('dialog')?.open).toBe(true)
  expect(host.querySelector('.coach-gloss')?.textContent).toBe('bien; bon')
  expect(localStorage.getItem(progressKey('coach'))).toBeNull()
  expect(loadWords('coach').ดี.strength).toBe(0)
  await act(() => host.querySelector<HTMLButtonElement>('[aria-label="Fermer"]')!.click())
  await act(() => speech.speak.mock.calls[0][2]('ended'))
  await act(() => answer('Très bien.').click())
  expect(loadProgress('coach')[questions[0].id].streak).toBe(0)
  expect(loadWords('coach').ดี.strength).toBe(0)
})
it('limits content to the admin, with a development-only preview and no lesson autoplay in the table', async () => {
  window.location.pathname = '/padel-coach/content'; account.finish.mockResolvedValue({ id: PETA_ACCOUNT_ID })
  await act(() => root.render(<CoachPage />))
  expect(host.querySelectorAll('tbody tr')).toHaveLength(128)
  expect(host.querySelector('th[lang="en"]')?.textContent).toBe('English')
  expect(host.querySelectorAll('tbody td[lang="en"]')).toHaveLength(128)
  expect(host.querySelector('tbody td[lang="en"]')?.textContent).toBe('Very good.')
  expect(host.querySelector('a[aria-label="Pratique"]')?.getAttribute('href')).toBe('/padel-coach')
  expect(speech.speak).not.toHaveBeenCalled()
  await act(() => root.unmount()); root = createRoot(host)
  account.finish.mockResolvedValue({ id: 'coach' })
  await act(() => root.render(<CoachPage />))
  expect(host.querySelector('table')).toBeNull(); expect(host.querySelector('nav')).toBeNull()
  await act(() => root.unmount()); root = createRoot(host)
  account.finish.mockResolvedValue(null); vi.stubEnv('DEV', false); window.location.pathname = '/padel-coach/preview/content'
  await act(() => root.render(<CoachPage />))
  expect(host.querySelector('table')).toBeNull(); expect(host.querySelector('.hotel-line')).not.toBeNull()
  await act(() => root.unmount()); root = createRoot(host)
  vi.stubEnv('DEV', true)
  await act(() => root.render(<CoachPage />))
  expect(host.querySelectorAll('tbody tr')).toHaveLength(128)
})
it('uses the shared identity flow, a distinct allowlisted mode, and a one-use ticket', async () => {
  expect(isCoachLineEntry(new URL(coachLineEntryUrl(true)).search)).toBe(true)
  expect(new URL(coachLineEntryUrl(true)).searchParams.get('intent')).toBe('signup')
  expect(isCoachLineEntry('?liff.state=%3Fapp%3Denglishsuccess%26mode%3Dpadel-coach')).toBe(true)
  expect(isCoachLineEntry('?app=englishsuccess&mode=padel')).toBe(false)
  window.location.hash = '#ticket=single-use'; account.finish.mockResolvedValue({ id: 'coach' })
  await act(() => root.render(<CoachPage />))
  expect(account.finish).toHaveBeenCalledWith('single-use'); expect(window.location.hash).toBe('')
  expect(window.location.pathname).toBe('/padel-coach')
})
it('rejects malformed progress and keeps word memory learner-specific', () => {
  localStorage.setItem(progressKey('coach'), JSON.stringify({ [questions[0].id]: { attempts: 1, correct: 99, streak: 99 } }))
  localStorage.setItem(memoryKey('coach'), JSON.stringify({ ดี: { seen: 1, strength: 99 } }))
  expect(loadProgress('coach')).toEqual({}); expect(loadWords('coach')).toEqual({})
  localStorage.setItem(memoryKey('coach'), JSON.stringify({ ดี: { seen: 8, strength: 8 } }))
  expect(loadWords('other')).toEqual({})
})
