 expect(host.querySelector('.cw-sentence-board')?.getAttribute('aria-label')).toBe('That is the phone.')
 await act(async()=>host.querySelector<HTMLButtonElement>('[data-word-role="determiner"]')!.click())
 expect([...host.querySelectorAll('.cw-word-chip')].map(button=>button.getAttribute('data-word'))).not.toContain('a')
