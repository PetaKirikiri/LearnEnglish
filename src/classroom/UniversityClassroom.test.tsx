it('keeps one shared header mounted across every tab and lesson, including game errors and education views',async()=>{
 calls.host.mockRejectedValue(new Error('Offline'))
 await act(async()=>root.render(<UniversityClassroom requestedLesson="lesson-6"/>))
 const header=host.querySelector('.cw-panel-header')
 expect(header?.parentElement?.classList.contains('su-class-panel')).toBe(true)
 for(const name of ['Testing','Game','Students','Whiteboard']){
  await click(name)
  expect(host.querySelectorAll('.cw-panel-header')).toHaveLength(1)
  expect(host.querySelector('.cw-panel-header')).toBe(header)
  expect(header?.textContent).toContain('06')
 }
 await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="Slot 1: What"]')!.click())
 expect(host.querySelector('.cw-word-heading h1')?.textContent).toBe('What')
 expect(host.querySelector('.cw-panel-header')).toBe(header)
 await act(async()=>host.querySelector<HTMLButtonElement>('.cw-word-return')!.click())
 expect(host.querySelector('.cw-panel-header')).toBe(header)
 await click('Game')
 await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="Previous lesson"]')!.click())
 expect(host.querySelector('.cw-panel-header')).toBe(header)
 expect(header?.textContent).toContain('05')
 expect(header?.textContent).toContain('Where are you going?')
 history.replaceState(null,'','/')
})

