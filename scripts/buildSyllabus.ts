// Reproducible generated data/migrations. Never changes the database itself.
import { writeFileSync } from 'node:fs'
import { config } from 'dotenv'
import { buildSyllabus } from '../src/curriculum/syllabus'
config({path:'.env.local',quiet:true})
const url=process.env.VITE_LANGUAGE_SUPABASE_URL!, key=process.env.VITE_LANGUAGE_SUPABASE_ANON_KEY!
if(new URL(url).hostname!=='gbsopnbovsxlstnmaaga.supabase.co') throw new Error('Expected SubtitleDisplay language project')
const r=await fetch(`${url}/rest/v1/rpc/englishsuccess_language`,{method:'POST',headers:{apikey:key,'Content-Type':'application/json'},body:'{}'})
if(!r.ok) throw new Error(`Dictionary read failed: ${r.status}`)
const dictionary=await r.json() as {words:{word:string;thai_gloss:string|null}[]}
const data=buildSyllabus(Object.fromEntries(dictionary.words.filter(w=>w.thai_gloss).map(w=>[w.word,w.thai_gloss!])))
writeFileSync('src/curriculum/syllabus.snapshot.json',JSON.stringify(data,null,2)+'\n')
const sql=(v:unknown)=>`'${JSON.stringify(v).replaceAll("'","''")}'::jsonb`
writeFileSync('supabase/language/20261019090600_general_listening_seed.sql',`-- TARGET: SubtitleDisplay gbsopnbovsxlstnmaaga. Generated by scripts/buildSyllabus.ts.
begin;
-- Reserve a collision-free range before applying the interleaved course order.
update public.englishsuccess_course_skills set position=position+1000 where course='hotel';
insert into public.englishsuccess_course_skills(course,skill,node_id,position)
select v->>'course',v->>'skill',v->>'nodeId',(v->>'order')::integer from jsonb_array_elements(${sql(data.courseSkills)}) v
on conflict(course,skill) do update set position=excluded.position;
insert into public.englishsuccess_course_questions(id,course,skill,position,payload)
select v->>'id','hotel',v->>'skill',ordinality::integer,v from jsonb_array_elements(${sql(data.questions)}) with ordinality q(v,ordinality)
on conflict(id) do nothing;
insert into public.englishsuccess_words(word,thai_gloss,lesson_thai_gloss,corpus_count,corpus_rank)
select v->>'word',v->>'thai',null,0,null from jsonb_array_elements(${sql(data.vocabulary)}) v on conflict(word) do nothing;
insert into public.englishsuccess_sentence_structures(id,node_id,payload)
select v->>'id',v->>'nodeId',v from jsonb_array_elements(${sql(data.structures)}) v on conflict(id) do update set payload=excluded.payload;
insert into public.englishsuccess_curriculum_vocabulary(word,payload)
select v->>'word',v from jsonb_array_elements(${sql(data.vocabulary)}) v on conflict(word) do update set payload=excluded.payload;
insert into public.englishsuccess_question_words(question_id,word,role)
select v->>'questionId',v->>'word',v->>'role' from jsonb_array_elements(${sql(data.wordLinks)}) v on conflict(question_id,word) do nothing;
update public.englishsuccess_curriculum_meta set revision='${data.revision}' where singleton;
commit;
`)
const newQuestions=data.questions.filter(q=>q.id.startsWith('hotel-g3-general-'))
writeFileSync('supabase/migrations/20261019090700_general_listening_questions.sql',`-- TARGET: shared accounts bknorpjoyxucrihnpyda. Add answer-validation IDs only.
begin;
insert into public.englishsuccess_hotel_questions(id,answer,active) values
${newQuestions.map(q=>`('${q.id}',${q.correct},true)`).join(',\n')}
on conflict(id) do nothing;
commit;
`)
console.log({sections:data.skills.length,frames:data.structures.reduce((n,s)=>n+s.frames.length,0),words:data.vocabulary.length,questions:data.questions.length,newQuestions:newQuestions.length})
