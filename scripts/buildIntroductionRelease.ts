// Generate release files only; never connects to or changes a live database.
import {readFileSync,writeFileSync} from 'node:fs'
import {buildSyllabus} from '../src/curriculum/syllabus'
const previous=JSON.parse(readFileSync('src/curriculum/syllabus.snapshot.json','utf8')) as {vocabulary:{word:string;thai:string}[]}
const data=buildSyllabus(Object.fromEntries(previous.vocabulary.map(w=>[w.word,w.thai])))
writeFileSync('src/curriculum/syllabus.snapshot.json',JSON.stringify(data,null,2)+'\n')
const questions=data.questions.filter(q=>q.id.startsWith('hotel-g3-general-introduction-'))
const ids=new Set(questions.map(q=>q.id))
const sql=(value:unknown)=>`'${JSON.stringify(value).replaceAll("'","''")}'::jsonb`
writeFileSync('supabase/language/20261025140000_introductions.sql',`-- Language DB only. Generated by scripts/buildIntroductionRelease.ts.
begin;
insert into public.englishsuccess_curriculum_skills(id,level,position,payload)
select v->>'id',v->>'level',(v->>'order')::integer,v from jsonb_array_elements(${sql(data.skills)}) v
on conflict(id) do update set payload=excluded.payload;
insert into public.englishsuccess_course_skills(course,skill,node_id,position)
select v->>'course',v->>'skill',v->>'nodeId',(v->>'order')::integer from jsonb_array_elements(${sql(data.courseSkills.filter(s=>s.nodeId.startsWith('meeting-')))}) v
on conflict(course,skill) do update set position=excluded.position;
insert into public.englishsuccess_course_questions(id,course,skill,position,payload)
select v->>'id','hotel',v->>'skill',row_number() over ()+${data.questions.length-questions.length},v from jsonb_array_elements(${sql(questions)}) v
on conflict(id) do update set payload=excluded.payload;
insert into public.englishsuccess_words(word,thai_gloss,lesson_thai_gloss,corpus_count,corpus_rank)
select v->>'word',v->>'thai',null,0,null from jsonb_array_elements(${sql(data.vocabulary)}) v on conflict(word) do nothing;
insert into public.englishsuccess_sentence_structures(id,node_id,payload)
select v->>'id',v->>'nodeId',v from jsonb_array_elements(${sql(data.structures)}) v on conflict(id) do update set payload=excluded.payload;
insert into public.englishsuccess_curriculum_vocabulary(word,payload)
select v->>'word',v from jsonb_array_elements(${sql(data.vocabulary)}) v on conflict(word) do update set payload=excluded.payload;
insert into public.englishsuccess_question_words(question_id,word,role)
select v->>'questionId',v->>'word',v->>'role' from jsonb_array_elements(${sql(data.wordLinks.filter(w=>ids.has(w.questionId)))}) v on conflict(question_id,word) do nothing;
update public.englishsuccess_curriculum_meta set revision='${data.revision}' where singleton;
commit;
`)
writeFileSync('supabase/migrations/20261025140100_introduction_answers.sql',`-- Shared accounts DB only: answer validation for the new English questions.
begin;
insert into public.englishsuccess_hotel_questions(id,answer,active) values
${questions.map(q=>`('${q.id}',${q.correct},true)`).join(',\n')}
on conflict(id) do update set answer=excluded.answer;
commit;
`)
console.log(`Prepared ${questions.length} introduction questions. No database changes applied.`)
