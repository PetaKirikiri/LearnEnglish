import {expect,it} from 'vitest'
import {memoryStore,roomAction} from './wordBattleCloud'
it('pairs two players, waits for host start, hides cards and synchronizes a full round',async()=>{
 const store=memoryStore();const time=1000000
 const host=await roomAction(store,'create',{name:'Teacher'},'',time)
 expect(host.players).toHaveLength(1);expect(host.start).toBe(0)
 await expect(roomAction(store,'start',{code:host.code,id:'start-before-join'},host.token!,time)).rejects.toThrow('Wait for')
 const guest=await roomAction(store,'join',{code:host.code,name:'Student'},'',time)
 expect(guest.players).toHaveLength(2)
 await expect(roomAction(store,'join',{code:host.code},'',time)).rejects.toThrow('two players')
 await expect(roomAction(store,'start',{code:host.code,id:'student-start'},guest.token!,time)).rejects.toThrow('host')
 const start=await roomAction(store,'start',{code:host.code,id:'host-start'},host.token!,time)
 expect(start.start).toBe(time+3000)
 await expect(roomAction(store,'buy',{code:host.code,id:'too-early',from:0,to:0},guest.token!,time)).rejects.toThrow('Wait for')
 const buy=await roomAction(store,'buy',{code:host.code,id:'first-buy',from:0,to:0},host.token!,time+4000)
 expect(buy.self.gold).toBe(7);expect(buy.self.board[0]?.word).toBe('the')
 const again=await roomAction(store,'buy',{code:host.code,id:'first-buy',from:0,to:0},host.token!,time+4000)
 expect(again.self.gold).toBe(7)
 await roomAction(store,'buy',{code:host.code,id:'second-buy',from:1,to:1},host.token!,time+4000)
 const visible=await roomAction(store,'state',{code:host.code},guest.token!,time+4000)
 expect(visible.rival?.board.slice(0,3)).toEqual([true,true,false]);expect(JSON.stringify(visible)).not.toContain('hash')
 expect(visible.rival?.shop).toEqual([false,false,true,true])
 const tick=await roomAction(store,'state',{code:host.code},host.token!,time+13000)
 expect(tick.self.gold).toBe(8)
 const end=await roomAction(store,'state',{code:host.code},host.token!,time+303000)
 expect(end.time).toBe(300);expect(end.self.gold).toBe(66)
 const later=await roomAction(store,'state',{code:host.code},host.token!,time+400000)
 expect(later.self.gold).toBe(end.self.gold)
 await expect(roomAction(store,'refresh',{code:host.code,id:'late-refresh'},host.token!,time+400000)).rejects.toThrow('finished')
 const restart=await roomAction(store,'rematch',{code:host.code,id:'new-round'},host.token!,time+400000)
 expect(restart.self.gold).toBe(8);expect(restart.self.board.filter(Boolean)).toHaveLength(0)
})
it('rejects invalid credentials and protects purchases during concurrent changes',async()=>{
 const store=memoryStore();const host=await roomAction(store,'create',{},'',1)
 await expect(roomAction(store,'state',{code:host.code},'wrong',2)).rejects.toThrow('Rejoin')
 await roomAction(store,'join',{code:host.code},'',2)
 await roomAction(store,'start',{code:host.code,id:'test-start'},host.token!,3)
 const requests=await Promise.allSettled([roomAction(store,'buy',{code:host.code,id:'buy-000001',from:0,to:0},host.token!,4000),roomAction(store,'buy',{code:host.code,id:'buy-000002',from:0,to:1},host.token!,4000)])
 expect(requests.filter(r=>r.status==='fulfilled')).toHaveLength(1)
 const view=await roomAction(store,'state',{code:host.code},host.token!,4000)
 expect(view.self.gold).toBe(7);expect(view.self.board.filter(Boolean)).toHaveLength(1)
})
